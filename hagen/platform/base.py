# -*- coding: utf-8 -*-
"""Пять розеток: всё, что программа просит у операционной системы.

Зачем это нужно. Обращения к Windows были рассыпаны по логике: `server.py`
звал `win_detect` из четырнадцати мест, `live.py` — из четырёх, и так далее,
всего сорок четыре точки. Из-за этого нельзя было ни посмотреть одним взглядом,
чего программа хочет от системы, ни подменить это на проверках, ни однажды
написать то же самое для другой ОС.

Здесь — только ОПИСАНИЕ: какие розетки есть и что каждая умеет. Реализации
лежат рядом: `windows/` — то, что работает сейчас, `fake/` — заглушки для
проверок. Выбор делает `hagen/platform/__init__.py`.

Розеток пять:

======== ==========================================================
Звук     поток с микрофона, поток с колонок, выбор устройства,
         выключатель микрофона, кружок микрофона на экране
Окна     активное окно, идёт ли звонок, куда звонок выводит звук,
         встреча из календаря
Ввод     горячая клавиша, вставка текста в чужое окно, капсула
Оболочка значок у часов, уведомления с кнопками, заставка, автозапуск
Система  переносимость папки, ярлыки, снимки экрана
======== ==========================================================

Почему описание — это `Protocol`, а не базовый класс. Реализация каждой
розетки — обычный модуль Python, а не объект: так уже написан весь код, и
переезд не должен требовать заворачивать его в классы. Модуль под `Protocol`
подходит по строению, наследовать ничего не надо, а проверка контракта
(`tests/t7_contracts.py`) всё равно видит, на месте ли имена.

Отдельное правило, которое легко потерять при переезде: **розетка НЕ должна
подключаться при импорте**. Сейчас почти все обращения написаны поздними
импортами внутри функций (`from . import win_detect` прямо в теле обработчика)
— и не случайно: иначе `pycaw`, `comtypes` и `win32com` грузились бы при каждом
запуске службы, даже когда возможность выключена. `platform/__init__.py`
подключает модуль розетки при первом обращении, а не при импорте пакета.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Callable, Protocol, runtime_checkable


# --------------------------------------------------------------- общие мелочи


@runtime_checkable
class Watcher(Protocol):
    """Фоновый наблюдатель: завёлся, живёт своим потоком, остановился.

    Так устроены сторож звонков и сторож папки снимков. Оба ничего не
    возвращают — говорят о событиях обработчиками, которые им дали.
    """

    def start(self) -> Any:
        """Запустить наблюдение."""

    def stop(self) -> Any:
        """Остановить. Звать можно и повторно, и после отказа при запуске."""


@runtime_checkable
class Recorder(Protocol):
    """Открытое устройство записи: отдаёт куски звука в обработчик.

    Куски приходят из служебного потока: 16 кГц, моно, float32. Тяжёлую работу
    в обработчике делать нельзя — следующий кусок не дождётся.
    """

    #: Как устройство зовёт Windows. Нужно для журнала и для проверки на эхо.
    device_name: str
    #: Номер устройства, на котором в итоге открылись.
    device_index: int | None
    #: Почему выбрано именно это устройство («устройство звонка», «по
    #: умолчанию»). Пусто — выбирать было не из чего.
    choice: str

    def start(self) -> Any:
        """Открыть устройство и начать отдавать звук. Не вышло — исключение."""

    def stop(self) -> Any:
        """Закрыть устройство."""


# ------------------------------------------------------------------ 1. Звук


@runtime_checkable
class Audio(Protocol):
    """Звук: что слышит микрофон, что уходит в колонки, выключен ли микрофон.

    Самая большая розетка. Под ней два разных пути записи, и оба нужны:
    свой (WASAPI из этого же процесса) и запасной (ffmpeg отдельной программой).
    Свой лучше — для доступа к звуку достаточно доверять одному файлу
    `python.exe` из папки программы, — но открывается не на всяком устройстве.
    """

    # -------- какие устройства есть

    def list_input_devices(self) -> list[dict[str, Any]]:
        """Микрофоны: `index`, `name`, `channels`, `is_default`, `is_communications`.

        Список берётся оттуда же, откуда идёт запись. Если строить его другим
        способом, имена в списке и при записи совпадут не всегда, и выбранное
        человеком устройство при записи не найдётся.
        """

    def list_loopback_devices(self) -> list[dict[str, Any]]:
        """Устройства вывода, с которых можно снять петлю (звук собеседников)."""

    def list_ffmpeg_devices(self, refresh: bool = False) -> list[dict[str, Any]]:
        """Запасной список — глазами ffmpeg. Нужен, когда свой путь пуст."""

    def default_render_devices(self) -> dict[str, str]:
        """Устройства вывода по умолчанию: мультимедиа и связь, по именам."""

    def default_mic_device(self) -> dict[str, Any] | None:
        """Микрофон по умолчанию для запасного пути."""

    def find_device(self, needle: str | None) -> dict[str, Any] | None:
        """Устройство по куску имени. Пусто — ничего не искали."""

    def recommended_input_index(self) -> int | None:
        """Какой микрофон писать, если в настройках номер не закреплён."""

    def same_device(self, a: str, b: str) -> bool:
        """Одно ли это устройство, хотя имена написаны по-разному.

        Нужна сторожу: он раз в несколько секунд сверяет, туда ли выводит звук
        программа звонка. Раньше логика лезла за этим в приватную часть звука.
        """

    def echo_risk(self, name: str, form: int | None = None) -> dict[str, Any]:
        """Услышит ли микрофон собеседников из этого устройства: `risk`, `why`.

        Зависит от УСТРОЙСТВА, а не от программы: у гарнитуры своё подавление
        эха, у встроенных динамиков его нет — и половина чужих фраз попадает в
        стенограмму как свои.
        """

    # -------- запись

    def open_mic(self, device_index: int | None,
                 on_audio: Callable[[Any], Any]) -> Recorder:
        """Микрофон своими силами (WASAPI в этом процессе)."""

    def open_loopback(self, device_index: int | None, on_audio: Callable[[Any], Any],
                      keep_alive: bool = True, open_retries: int = 1,
                      want_name: str | None = None) -> Recorder:
        """Петля вывода в ЭТОМ процессе. Так работает процесс-помощник."""

    def open_loopback_process(self, device_index: int | None,
                              on_audio: Callable[[Any], Any],
                              want_name: str | None = None) -> Recorder:
        """Петля вывода через отдельный процесс-помощник.

        Помощник нужен не для красоты: долгоживущий процесс через раз получал
        от Windows «Invalid device», и вылечило это только открытие петли в
        свежем процессе.
        """

    def open_ffmpeg(self, device: dict[str, Any], on_audio: Callable[[Any], Any],
                    label: str) -> Recorder:
        """Запасной путь: ffmpeg пишет в канал, мы читаем куски по 100 мс."""

    # -------- пробы и разбор отказов

    def probe_input(self, device_index: int | None = None,
                    seconds: float = 0.8) -> dict[str, Any]:
        """Короткая проба микрофона: `ok`, `peak`, `reason`.

        Пробуется КАЖДЫЙ микрофон, а не только выбранный: виртуальные
        устройства исправно открываются и отдают ровные нули, и отличить их от
        живого входа можно только послушав.
        """

    def probe_loopback_process(self, device_index: int | None = None,
                               seconds: float = 1.2) -> dict[str, Any]:
        """Проба петли тем же путём, которым идёт запись, — через помощника."""

    def diagnose(self) -> dict[str, Any]:
        """Что служба видит в звуковом стеке и что мешает открыть запись."""

    def diag_ffmpeg(self, seconds: float = 0.6) -> dict[str, Any]:
        """То же для запасного пути: полный протокол запуска ffmpeg."""

    # -------- выключатель микрофона

    def mic_state(self) -> dict[str, Any]:
        """Выключен ли микрофон Windows: `available`, `muted`."""

    def mic_set_muted(self, muted: bool) -> dict[str, Any]:
        """Выключить или включить микрофон Windows целиком."""

    def mic_toggle(self) -> dict[str, Any]:
        """Переключить. Состояние неизвестно — считаем, что включён."""

    # -------- кружок микрофона поверх окон

    def mic_pill(self, on_click: Callable[[], Any],
                 on_change: Callable[[dict[str, Any]], Any]) -> Any:
        """Кружок поверх всех окон: цвет говорит про микрофон, движение — про запись.

        Объект умеет `show(muted, recording)`, `hide()`, `set_muted(muted)`.
        Его не видят ни демонстрация экрана, ни запись экрана, ни снимок.
        """


# ------------------------------------------------------------------ 2. Окна


@runtime_checkable
class Desktop(Protocol):
    """Что сейчас происходит на компьютере: звонок, встреча, куда идёт звук.

    Имя «desktop» — про рабочий стол целиком, а не про одно окно: розетка
    отвечает и за аудиосессии, и за календарь. Назвать её `windows` нельзя —
    так называется папка с реализацией.
    """

    def current_meeting(self, window_minutes: int | None = None,
                        start_outlook: bool = False,
                        with_alternatives: bool = False) -> dict[str, Any] | None:
        """Встреча, которая идёт сейчас или вот-вот начнётся.

        Только идущая или ближайшая: закончившаяся встреча имени записи не даёт.
        Из нескольких подходящих — та, что начинается ближе к этому моменту:
        встречи в календаре стоят внахлёст, и звонок за минуту до новой — её
        начало, а не середина прошлой.
        Пояс времени берётся из самой встречи, а не из системы, — иначе встреча
        по московскому времени приезжает как «то же время по Гринвичу» и запись
        получает имя встречи, которая была тремя часами раньше.

        `with_alternatives` — положить в ответ `alternatives`: остальные
        подходящие по времени встречи (не больше двух), чтобы человек мог
        переключить запись на нужную.
        """

    def suggest_title(self, meeting: dict[str, Any] | None) -> str:
        """Имя записи: тема встречи, а без встречи — дата и время."""

    def suggest_max_speakers(self, meeting: dict[str, Any] | None) -> int | None:
        """Сколько голосов ждать при разметке: от 2 до 10 по числу приглашённых."""

    def attendee_names(self, meeting: dict[str, Any] | None) -> list[str]:
        """Имена приглашённых. Встречи нет — пустой список."""

    def outlook_kind(self) -> dict[str, Any]:
        """Какой Outlook стоит: у классического есть `com_available`, у нового нет."""

    def compose_mail(self, subject: str, body: str,
                     attachments: list[str] | None = None,
                     to: list[str] | None = None) -> bool:
        """Открыть НОВОЕ ПИСЬМО в почтовой программе и показать его человеку.

        Письмо только показывается, а не отправляется: отправка наружу —
        действие необратимое, и последнее слово за человеком.

        Так вложение и доезжает: длина ссылки `mailto:` ограничена тысячами
        знаков, и протокол часовой встречи через неё не передать. Возвращает
        False, если такого письма собрать нечем (нет классического Outlook), —
        тогда ядро уходит на путь `mailto:` с коротким текстом.
        """

    def detect_call(self) -> dict[str, Any]:
        """Идёт ли прямо сейчас звонок и какая программа его ведёт.

        Программа звонка — та, что ДЕРЖИТ МИКРОФОН. Иначе любое видео в браузере
        уводило бы запись собеседников от программы совещаний.
        """

    def call_output_device(self, sessions: list[dict[str, Any]] | None = None,
                           holders: set[str] | None = None) -> dict[str, Any] | None:
        """Куда программа звонка выводит звук сейчас. Нет звонка — пусто.

        `sessions` и `holders` задаются только проверками: в живой работе
        розетка смотрит сама.
        """

    def watch_calls(self, on_call_start: Callable[[dict[str, Any]], Any],
                    on_call_end: Callable[[dict[str, Any]], Any]) -> Watcher:
        """Сторож звонков: зовёт обработчики на начале и конце."""

    def list_sessions(self) -> list[dict[str, Any]]:
        """Аудиосессии устройств вывода: кто сейчас звучит."""

    def list_capture_sessions(self) -> list[dict[str, Any]]:
        """Аудиосессии микрофонов: кто сейчас держит микрофон."""


# ------------------------------------------------------------------ 3. Ввод


@runtime_checkable
class Hotkey(Protocol):
    """Разобранное сочетание клавиш."""

    #: Битовая маска модификаторов, как её ждёт система.
    mods: int
    #: Код обычной клавиши. 0 — сочетание из одних модификаторов.
    vk: int
    #: Как показать человеку: «Ctrl + Shift + Space».
    text: str

    @property
    def by_hook(self) -> bool:
        """Нужен ли для этого сочетания общий перехват клавиатуры.

        Сочетание из одних модификаторов обычным способом поймать нельзя:
        система принимает заявку без ошибки, но о нажатии не сообщает никогда.
        """


@runtime_checkable
class Input(Protocol):
    """Ввод: горячая клавиша, вставка текста в чужое окно, капсула на экране.

    Здесь живёт только разговор с системой. Сама диктовка — что записать, когда
    спать, что делать с текстом — остаётся логикой и сюда не переезжает.
    """

    def parse_hotkey(self, raw: str) -> Hotkey:
        """«ctrl+shift+space» → сочетание. Непонятное — ValueError с текстом для человека."""

    def format_hotkey(self, mods: int, vk: int) -> str:
        """Обратно в строку для показа."""

    def listen(self, hotkey: Hotkey, on_press: Callable[[], Any],
               on_release: Callable[[float], Any] | None = None) -> Watcher:
        """Занять сочетание и звать обработчики.

        Обычное сочетание занимается поимённо — программа не видит ничего,
        кроме него. Сочетание из одних модификаторов требует общего перехвата,
        и он поднимается ТОЛЬКО если человек сам такое выбрал: перехват видит
        каждое нажатие в системе, так устроены программы для кражи паролей, и
        антивирус относится к ним соответственно.
        """

    def paste_text(self, text: str, restore: bool = True) -> bool:
        """Вставить текст в окно, которое сейчас впереди.

        Через буфер обмена и «вставить», а прежнее содержимое буфера
        возвращается. Набор по буквам в чужих окнах теряет символы и зависит
        от раскладки.
        """

    def click(self, which: str) -> None:
        """Короткий щелчок «начал» или «закончил». Не прозвучал — не беда."""

    def capsule(self) -> Any:
        """Капсула диктовки: окошко «слушаю…» поверх всех окон.

        Умеет `show(state, text)`, `hide()`. Своё окно нужно потому, что диктуют
        в чужую программу, а окно Hagen в этот момент обычно спрятано в трей.
        """


# -------------------------------------------------------------- 4. Оболочка


@runtime_checkable
class Shell(Protocol):
    """Оболочка: значок у часов, уведомления с кнопками, заставка, автозапуск, окна-вопросы."""

    def icon_paths(self) -> dict[str, Path]:
        """Пути к значкам по состояниям программы. Нет файла — состояние пропускаем."""

    def autostart_enabled(self, folder: Path | None = None) -> bool:
        """Стоит ли программа в автозапуске."""

    def set_autostart(self, enabled: bool, folder: Path | None = None) -> dict[str, Any]:
        """Поставить или убрать автозапуск. Делается сразу, а не при следующем запуске."""

    def sync_autostart(self) -> None:
        """Привести автозапуск в соответствие с настройкой."""

    def app_shell(self, window: Any, server_mod: Any) -> Any:
        """Связка окна программы, значка и уведомлений.

        Умеет `start()`, `open_window()`, держит поле `notifier`.
        """

    def make_notifier(self, server_mod: Any, on_open: Callable[[], Any]) -> Any | None:
        """Уведомления с кнопками. Нет — программа работает, просто молча."""

    def ask_yes_no(self, title: str, text: str) -> bool:
        """Вопрос «Да/Нет» окном системы: окно программы может быть спрятано."""

    def pick_folder(self, title: str, start: str | None = None) -> str | None:
        """Выбрать папку окном системы — тем же, каким её выбирают в Проводнике.

        `start` — где окно откроется; такой папки нет — ближайшая существующая
        выше. Возвращает полный путь или None, если человек передумал. Окно не
        открылось — исключение: вызывающий предложит вписать путь руками.

        Зовётся и установщиком, когда окружения программы ещё нет, поэтому
        обходится стандартной библиотекой Python.
        """

    def show_error(self, title: str, text: str) -> None:
        """Сообщить об ошибке окном системы.

        Нужна там, где больше сказать негде: консоль спрятана, окно программы
        ещё не поднялось или уже не поднимется. Поэтому обязана работать, даже
        когда остальная программа не загрузилась.
        """

    def focus_existing(self, title: str) -> bool:
        """Поднять уже открытое окно программы вместо второго запуска.

        True — нашли и подняли. Своё собственное окно не считается.
        """

    def splash_show(self) -> Any | None:
        """Заставка на время запуска. Не показалась — и ладно."""

    def splash_close(self) -> None:
        """Убрать заставку. Запуск при этом не задерживается ни на миг."""


# --------------------------------------------------------------- 5. Система


@runtime_checkable
class System(Protocol):
    """Система: переносимость папки, ярлыки, снимки экрана."""

    def ensure_portable(self, shortcuts: bool = True) -> dict[str, Any]:
        """Всё, что нужно для работы из текущей папки: пути и ярлыки.

        Папку могли перенести на другой компьютер или просто в другое место —
        пути к Python и ярлыки чинятся сами. Дёшево, зовётся при каждом запуске.
        """

    def write_shortcut(self, link: Path, arguments: str, description: str,
                       icon: str | None = None) -> None:
        """Написать ярлык на программу."""

    def make_shortcuts(self, folders: dict[str, Path] | None = None) -> list[str]:
        """Ярлыки «Hagen» на рабочем столе и в «Пуске», со значком программы.

        Ставит установщик (run.py --shortcuts). Уже есть — пишутся заново, на
        эту папку. ``folders`` — куда класть вместо системных папок (для
        проверок). Возвращает пути созданных ярлыков.
        """

    def screenshot_folders(self, auto: bool = False) -> list[Path]:
        """Куда система сама складывает снимки экрана. Настройка сильнее догадки.

        Только существующие папки. `auto` — одна догадка, без настройки: что
        программа нашла бы сама, если список папок не задан.
        """

    def watch_screenshots(self, rec_id: str, position_s: Callable[[], float],
                          on_shot: Callable[[dict[str, Any]], Any]) -> Watcher:
        """Сторож снимков на время записи: новый снимок — в запись по времени."""

    def delete_shots(self, rec_id: str) -> int:
        """Убрать файлы снимков записи. Только свои."""

    def shift_shots(self, items: list[dict[str, Any]],
                    offset_s: float) -> list[dict[str, Any]]:
        """Сдвинуть время снимков при склейке дописанной части к записи.

        Система здесь ни при чём: это арифметика, которая оказалась рядом со
        снимками. Место ей в логике записей — но переносить её туда значило бы
        переделывать, а не перевозить.
        """

    def hidden_process_flags(self) -> int:
        """Флаги запуска дочерней программы (ffmpeg, Claude CLI) без окна консоли.

        Отдаётся в `creationflags` у `subprocess`. Без них на каждый вызов на
        экране мигает чёрное окно. На системе, где такого окна не бывает, — 0.
        """

    def set_process_priority(self, pid: int, level: str) -> bool:
        """Сколько процессора отдавать своей дочерней программе. Менять можно на ходу.

        `level`: "normal" — как всем; "low" — ниже среднего: Windows сначала
        отдаёт процессор остальным, а свободный остаток — ей, так что без
        нагрузки она почти не замедляется; "lowest" — как «Режим
        эффективности» в Диспетчере задач: самый низкий приоритет и
        экономичные ядра на пониженной частоте. True — получилось.
        """

    def open_path(self, path: str | Path) -> None:
        """Открыть файл или папку программой, которая стоит для них по умолчанию."""

    def open_link(self, url: str) -> None:
        """Открыть ссылку программой, назначенной её виду.

        Не то же, что `open_path`: здесь не файл, а адрес со схемой —
        `mailto:` открывает почтовую программу, `tg://` — Telegram. Разрешены
        только схемы из `LINK_SCHEMES`: система запускает то, что назначено
        схеме в реестре, и чужая ссылка запустила бы неизвестно что.
        """

    def set_console_title(self, text: str) -> None:
        """Заголовок окна консоли.

        Пусковой файл написан латиницей — иначе интерпретатор команд рвёт
        кириллицу, — поэтому русский заголовок ставится отсюда.
        """

    def hide_console(self) -> None:
        """Спрятать окно консоли: в режиме приложения оно не нужно."""

    def restrict_to_owner(self, path: str | Path) -> None:
        """Оставить файл доступным только владельцу учётной записи.

        Так хранится файл с ключами сервисов. Не вышло — молча: ключи от этого
        не теряются, просто защищены слабее.
        """


